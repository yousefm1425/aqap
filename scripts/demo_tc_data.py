def gdate(sem: int, week: int, day: int = 0) -> date:
    return S_START[sem] + timedelta(days=7 * (week - 1) + day)


def hdate(sem: int, week: int, day: int = 0) -> str:
    y, m, d = H_START[sem]
    n = d - 1 + 7 * (week - 1) + day
    m += n // 30
    d = n % 30 + 1
    if m > 12:
        y, m = y + 1, m - 12
    return f"{y}/{m:02d}/{d:02d}هـ"



def _roster() -> list[dict]:
    out, seen = [], set()
    for lvl in sorted(LEVELS):
        for spec in SPECS:
            n = LEVELS[lvl][spec][0]
            year = {1: 447, 2: 446, 3: 446, 4: 445, 5: 445}[lvl]
            for i in range(n):
                while True:
                    nm = f"{R.choice(FIRST)} {R.choice(FIRST)} {R.choice(FAMILY)}"
                    if nm not in seen and nm.split()[0] != nm.split()[1]:
                        seen.add(nm)
                        break
                cg = round(min(5.0, max(1.6, R.gauss(3.55 if lvl > 1 else 3.4, 0.62))), 2)
                out.append({"no": f"{year}{R.randint(10000, 99999)}{len(out) % 10}", "name": nm, "spec": spec, "level": lvl,
                            "cgpa": cg})
    advisors_by_spec = {A: [a for a in ADVISORS if a in TN[:8]], B: [a for a in ADVISORS if a in TN[8:]]}
    for spec in SPECS:
        group = [t for t in out if t["spec"] == spec]
        for i, t in enumerate(group):
            t["advisor"] = advisors_by_spec[spec][i % len(advisors_by_spec[spec])]
    return out


ROSTER = _roster()



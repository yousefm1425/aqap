EV = "@EV"
DONE, PART, NOT = "مُنفذ", "مُنفذ جزئي", "لم يُنفذ"
BUILDERS: dict = {}


def form(code):
    def deco(fn):
        BUILDERS[code] = fn
        return fn
    return deco


def task(sem, week, text, target, mech, owner, day=0, status=DONE, achieved=None, obstacles=None, improve=None):
    if achieved is None and isinstance(target, (int, float)):
        achieved = target if status == DONE else (round(target * 0.6) if status == PART else 0)
    return {"semester": SEM[sem], "week": WEEKS[week - 1], "task": text, "target": target, "mechanism": mech, "owner": owner,
            "date": hdate(sem, week, day), "status": status, "achieved": achieved, "obstacles": obstacles, "improve": improve}


def imp(rec, action, sem, week, owner, status=DONE, obstacles=None, solutions=None, **kw):
    return {"recommendation": rec, "action": action, "date": hdate(sem, week), "owner": owner, "evidence": EV,
            "status": status, "obstacles": obstacles, "solutions": solutions, **kw}


def fixed(schema: dict, key: str) -> list[dict]:
    return next(s for s in schema["sections"] if s["key"] == key)["fixed_rows"]


